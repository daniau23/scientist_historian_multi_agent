"""Minimal ``.ipynb`` -> ``.py`` converter.

Notebooks are plain JSON, so no extra dependency (e.g. ``nbformat``) is
required.  IPython magics and shell escapes are stripped so the result is
valid, runnable Python.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Dict, List

# ``REPO_ROOT`` holds the project; the source ``*.ipynb`` files live in the
# ``notebooks`` sub-folder.
REPO_ROOT = Path(__file__).resolve().parent.parent
NOTEBOOKS_DIR = REPO_ROOT / "notebooks"
# Default output directory for converted files.
CONVERTED_DIR = Path(__file__).resolve().parent / "converted"

# Any line starting with ``%`` (magic) or ``!`` (shell) is kernel syntax and
# cannot run under plain ``python``, so it is removed during conversion.
_MAGIC_RE = re.compile(r"^\s*[%!]")
# Visual separator printed between converted cells.
_CELL_SEP = "# " + "-" * 74


def notebook_to_source(notebook: Dict) -> str:
    """Convert a parsed notebook JSON document into Python source."""
    lines: List[str] = [
        "# Auto-generated by scripting.convert - do not edit by hand.",
    ]
    for index, cell in enumerate(notebook.get("cells", [])):
        # Markdown cells carry no executable code; only ``code`` cells matter.
        if cell.get("cell_type") != "code":
            continue

        # Notebooks store source either as a single string or a list of lines.
        source = "".join(cell.get("source", []))
        # Drop IPython-only lines (see ``_MAGIC_RE``) and skip empty cells.
        cleaned_lines = [
            line for line in source.splitlines() if not _MAGIC_RE.match(line)
        ]
        cleaned = "\n".join(cleaned_lines).strip("\n")
        if not cleaned.strip():
            continue

        # Delimit each cell so readers (and the generated file) mirror the
        # original notebook structure.
        lines.append(_CELL_SEP)
        lines.append(f"# cell[{index}]")
        lines.append(_CELL_SEP)
        lines.append(cleaned)
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def convert_notebook(ipynb_path: str | Path, out_dir: str | Path | None = None) -> Path:
    """Convert a single notebook and return the written ``.py`` path."""
    ipynb_path = Path(ipynb_path)
    out_dir = Path(out_dir) if out_dir is not None else CONVERTED_DIR
    # Ensure the destination directory exists before writing.
    out_dir.mkdir(parents=True, exist_ok=True)

    # Notebook files are JSON documents; parse them without any third-party lib.
    with ipynb_path.open("r", encoding="utf-8") as handle:
        notebook = json.load(handle)

    # The output keeps the notebook stem (``foo.ipynb`` -> ``foo.py``).
    out_path = out_dir / (ipynb_path.stem + ".py")
    out_path.write_text(notebook_to_source(notebook), encoding="utf-8")
    return out_path


def convert_all(
    root: str | Path | None = None, out_dir: str | Path | None = None
) -> List[Path]:
    """Convert every ``.ipynb`` under ``root`` (non-recursive).

    Defaults to the ``notebooks`` folder, which is where the source notebooks
    live.  Returns the list of written paths so the CLI can report what it
    produced.
    """
    root = Path(root) if root is not None else NOTEBOOKS_DIR
    outputs: List[Path] = []
    # Sort for deterministic output ordering.
    for ipynb in sorted(root.glob("*.ipynb")):
        outputs.append(convert_notebook(ipynb, out_dir))
    return outputs